import http from 'node:http';
import {readFile, writeFile, rename, mkdir} from 'node:fs/promises';
import {existsSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawn} from 'node:child_process';

const dir=path.dirname(fileURLToPath(import.meta.url));
const project=path.resolve(dir,'..');
const stateFile=path.join(dir,'state.json');
const tsState=path.join(project,'src','config','editorState.ts');
const uploadedDir=path.join(project,'public','images');
const mime={'.html':'text/html; charset=utf-8','.mjs':'text/javascript; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8','.json':'application/json; charset=utf-8','.png':'image/png','.jpg':'image/jpeg','.jpeg':'image/jpeg','.webp':'image/webp'};
const parseBody=async(req)=>{
 let total=0; const chunks=[];
 for await(const c of req){total+=c.length;if(total>12*1024*1024)throw Error('Request terlalu besar');chunks.push(c);}
 return JSON.parse(Buffer.concat(chunks).toString('utf8'));
};
const respond=(res,status,body,type='application/json; charset=utf-8')=>{res.writeHead(status,{'Content-Type':type,'Cache-Control':'no-store','X-Content-Type-Options':'nosniff'});res.end(typeof body==='string'||Buffer.isBuffer(body)?body:JSON.stringify(body));};
const safeName=(s)=>typeof s==='string'&&/^[a-zA-Z0-9_.-]{1,100}$/.test(s)&&!s.startsWith('.')&&s!=='..';
const allLayerIds=async()=>{
 const keys=new Set();for(let i=1;i<=6;i++){
  const data=JSON.parse(await readFile(path.join(dir,'data',`scene${String(i).padStart(2,'0')}.json`),'utf8'));
  for(const l of data.layers)keys.add(`S${String(i).padStart(2,'0')}:${l.id}`);
 }return keys;
};
let knownIds=await allLayerIds();
const cleanLayer=(p)=>{
 const fields=['x','y','scale','rotation','opacity','width','height','zIndex','startFrame','endFrame','fontSize','fontWeight','letterSpacing','strokeWidth','animationStartFrame','delayFrames','durationFrames'];
 const output={};
 for(const f of fields)if(p[f]!==undefined){const n=Number(p[f]);if(Number.isFinite(n)&&Math.abs(n)<100000)output[f]=n;}
 for(const f of ['fill','stroke','fontFamily','text','asset'])if(typeof p[f]==='string'&&p[f].length<=1000)output[f]=p[f];
 for(const f of ['visible'])if(typeof p[f]==='boolean')output[f]=p[f];
 if(['linear','ease-in-out'].includes(p.easing))output.easing=p.easing;
 if(['fade','slide-up','pop','wipe'].includes(p.animation))output.animation=p.animation;
 if(Array.isArray(p.keyframes))output.keyframes=p.keyframes.filter(k=>Number.isInteger(k.frame)&&k.frame>=0&&k.frame<=480).slice(0,100).map(k=>{
  const item={frame:k.frame};for(const f of ['x','y','scale','rotation','opacity'])if(Number.isFinite(k[f]))item[f]=k[f];return item;
 });
 return output;
};
const openBrowser=(url)=>{
 try{let process;
  if(globalThis.process.platform==='win32')process=spawn('cmd',['/c','start','',url],{detached:true,stdio:'ignore'});
  else if(globalThis.process.platform==='darwin')process=spawn('open',[url],{detached:true,stdio:'ignore'});
  else process=spawn('xdg-open',[url],{detached:true,stdio:'ignore'});
  process.on('error',()=>{});process.unref();
 }catch{}
};
const server=http.createServer(async(req,res)=>{
 const method=req.method??'GET';
 const pathname=new URL(req.url??'/', 'http://localhost').pathname;
 try{
  if(method==='GET'&&pathname==='/api/state')return respond(res,200,JSON.parse(await readFile(stateFile,'utf8')));
  if(method==='POST'&&pathname==='/api/state'){
   const received=await parseBody(req);const layers=received?.layers;
   if(!layers||typeof layers!=='object'||Array.isArray(layers))return respond(res,400,{error:'Format layer tidak valid'});
   const safe={version:2,layers:{}};
   for(const [id,p] of Object.entries(layers)){
    if(!knownIds.has(id))return respond(res,400,{error:`Layer tidak ditemukan: ${id}`});
    if(!p||typeof p!=='object'||Array.isArray(p))continue;
    safe.layers[id]=cleanLayer(p);
   }
   const json=JSON.stringify(safe,null,2)+'\n';
   const ts=`import type {LayerOverrides} from './props';\n/** AUTO-GENERATED by visual editor; changes are persistent and used by Remotion preview/render. */\nexport const EDITOR_LAYER_OVERRIDES:LayerOverrides = ${JSON.stringify(safe.layers,null,2)};\n`;
   await writeFile(stateFile+'.tmp',json);await rename(stateFile+'.tmp',stateFile);
   await writeFile(tsState+'.tmp',ts);await rename(tsState+'.tmp',tsState);
   return respond(res,200,{saved:true,count:Object.keys(safe.layers).length});
  }
  if(method==='POST'&&pathname==='/api/upload'){
   const payload=await parseBody(req);const name=payload?.name;
   if(!safeName(name)||!/\.(png|jpg|jpeg|webp)$/i.test(name))return respond(res,400,{error:'Gunakan PNG/JPG/WEBP, nama file sederhana'});
   const bytes=Buffer.from(payload.data??'', 'base64');
   if(!bytes.length||bytes.length>8*1024*1024)return respond(res,400,{error:'Gambar harus berukuran 1 byte–8MB'});
   await mkdir(uploadedDir,{recursive:true});await writeFile(path.join(uploadedDir,name),bytes);
   return respond(res,200,{name});
  }
  if(method==='GET'&&pathname.startsWith('/assets/images/')){
   const file=decodeURIComponent(pathname.slice('/assets/images/'.length));
   if(!safeName(file))return respond(res,404,'Not found','text/plain');
   const p=path.join(uploadedDir,file);if(!existsSync(p))return respond(res,404,'Not found','text/plain');
   return respond(res,200,await readFile(p),mime[path.extname(p).toLowerCase()]??'application/octet-stream');
  }
  if(method==='GET'){
   const name=pathname==='/'?'index.html':decodeURIComponent(pathname.slice(1));
   if(name.includes('..')||path.isAbsolute(name)||name.includes('\\'))return respond(res,403,'Forbidden','text/plain');
   const p=path.resolve(dir,name);
   if(!p.startsWith(dir+path.sep)&&p!==path.join(dir,'index.html'))return respond(res,403,'Forbidden','text/plain');
   if(!existsSync(p))return respond(res,404,'Not found','text/plain');
   return respond(res,200,await readFile(p),mime[path.extname(p).toLowerCase()]??'application/octet-stream');
  }
  return respond(res,405,'Method not allowed','text/plain');
 }catch(err){respond(res,500,{error:String(err?.message??err)});}
});
let port=4178;
const listen=()=>server.listen(port,'127.0.0.1',()=>{const url=`http://127.0.0.1:${port}`;console.log(`\nEASY2BOOT VISUAL EDITOR: ${url}\nTekan Ctrl+C untuk berhenti.\n`);openBrowser(url);});
server.on('error',err=>{if(err.code==='EADDRINUSE'&&port<4190){port++;listen();}else console.error(err);});
listen();
